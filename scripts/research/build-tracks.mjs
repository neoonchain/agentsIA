// Builds src/lib/examples-dip.js and src/lib/examples-trend.js: the Dip buyer and Trend rider paper tracks on real Coinbase
// daily candles (fetch them with fetch-daily-long.mjs), $5,000 each, from FROM to the last completed day TO.
// The app continues both day by day from their saved state.
//   node build-tracks.mjs <daily-long.json> [FROM=2024-11-06] [TO=yesterday]
import fs from 'node:fs';
import { stepTrack, newTrack, trackDecision, summary, DAY } from '../../src/lib/dipbuyer.js';
import { stepTrend, newTrendTrack, trendDecision } from '../../src/lib/trendrider.js';

const [, , file, FROM = '2024-11-06', TO = new Date(Math.floor(Date.now() / DAY) * DAY - DAY).toISOString().slice(0, 10)] = process.argv;
const daily = JSON.parse(fs.readFileSync(file, 'utf8'));
for (const a of Object.keys(daily)) daily[a] = daily[a].filter(c => c.t <= Date.parse(TO));
const r = (v, d = 6) => +(+v).toPrecision(d), day = t => new Date(t).toISOString().slice(0, 10);
const tidy = st => ({ ...st, eq: +st.eq.toFixed(2), peak: +st.peak.toFixed(2), maxDD: +st.maxDD.toFixed(4) });
const head = name => `// Paper track of the ${name} rules on real Coinbase daily candles, ${FROM} to ${TO}, starting with $5,000.\n// Generated by scripts/research/build-tracks.mjs. The app continues it day by day from its saved state.\n`;
const report = (name, st, trades, eqEnd) => { const s = summary(trades); console.log(`${name}: ${s.n} trades, win ${(s.winRate * 100).toFixed(1)}%, PF ${s.profitFactor.toFixed(2)}, ${((eqEnd / st.start - 1) * 100).toFixed(1)}% (marked), max DD ${(st.maxDD * 100).toFixed(1)}%, open ${Object.keys(st.pos).join(', ') || 'none'}`); };

{ // Dip buyer
  const st = newTrack(Date.parse(FROM), 5000), days = []; let eqEnd = st.eq;
  const { trades } = stepTrack(st, daily, Date.parse(TO), d => { days.push(d); eqEnd = d.equity; });
  const rows = trades.map(t => [t.asset, day(t.t), day(t.closedT), r(t.entry), r(t.stop), r(t.tp), r(t.exit), r(t.qty, 5), +t.pnl.toFixed(2), +t.r.toFixed(2), t.why, t.days, t.ctx]);
  fs.writeFileSync(new URL('../../src/lib/examples-dip.js', import.meta.url), `${head('Dip buyer')}// [asset, opened, closed, entry, stop, target, exit, qty, pnl USD, R, exit reason, days, market context at the signal]
export const TRACK = ${JSON.stringify(rows).replace(/\],\[/g, '],\n[')};
export const TRACK_STATE = ${JSON.stringify(tidy(st))};
// The rules' decision on each of the last 30 days, newest first (shown in "How the AI decided").
export const TRACK_DECISIONS = ${JSON.stringify(days.slice(-30).reverse().map(trackDecision))};
`);
  report('Dip buyer', st, trades, eqEnd);
}
{ // Trend rider
  const st = newTrendTrack(Date.parse(FROM), 5000), days = []; let eqEnd = st.eq;
  const { trades } = stepTrend(st, daily, Date.parse(TO), d => { days.push(d); eqEnd = d.equity; });
  const rows = trades.map(t => [t.asset, day(t.t), day(t.closedT), r(t.entry), r(t.stop), r(t.exit), r(t.qty, 5), +t.pnl.toFixed(2), +t.r.toFixed(2), t.why, t.days, t.ctx]);
  fs.writeFileSync(new URL('../../src/lib/examples-trend.js', import.meta.url), `${head('Trend rider')}// [asset, opened, closed, entry, safety stop, exit, qty, pnl USD, R, exit reason, days, market context at the signal]
export const TREND_TRACK = ${JSON.stringify(rows).replace(/\],\[/g, '],\n[')};
export const TREND_STATE = ${JSON.stringify(tidy(st))};
export const TREND_DECISIONS = ${JSON.stringify(days.slice(-30).reverse().map(trendDecision))};
`);
  report('Trend rider', st, trades, eqEnd);
}
