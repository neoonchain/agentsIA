// Builds src/lib/examples-dip.js: the Dip buyer paper track on real Coinbase daily candles (fetch them with fetch-daily-long),
// from FROM to the last completed day TO. The app continues it day by day from TRACK_STATE.
//   node build-dip-track.mjs <daily-long.json> [FROM=2024-11-06] [TO=yesterday]
import fs from 'node:fs';
import { stepTrack, newTrack, trackDecision, summary, DAY } from '../../src/lib/dipbuyer.js';

const [, , file, FROM = '2024-11-06', TO = new Date(Math.floor(Date.now() / DAY) * DAY - DAY).toISOString().slice(0, 10)] = process.argv;
const daily = JSON.parse(fs.readFileSync(file, 'utf8'));
for (const a of Object.keys(daily)) daily[a] = daily[a].filter(c => c.t <= Date.parse(TO));
const state = newTrack(Date.parse(FROM)), days = [];
const { trades } = stepTrack(state, daily, Date.parse(TO), d => days.push(d));
const r = (v, d = 6) => +(+v).toPrecision(d), day = t => new Date(t).toISOString().slice(0, 10);
const rows = trades.map(t => [t.asset, day(t.t), day(t.closedT), r(t.entry), r(t.stop), r(t.tp), r(t.exit), r(t.qty, 5), +t.pnl.toFixed(2), +t.r.toFixed(2), t.why, t.days, t.ctx]);
const st = { ...state, eq: +state.eq.toFixed(2), peak: +state.peak.toFixed(2), maxDD: +state.maxDD.toFixed(4) };
const decisions = days.slice(-30).reverse().map(trackDecision);
fs.writeFileSync(new URL('../../src/lib/examples-dip.js', import.meta.url), `// Paper track of the Dip buyer rules (src/lib/dipbuyer.js) on real Coinbase daily candles, ${FROM} to ${TO}.
// Generated by scripts/research/build-dip-track.mjs. The app continues it day by day from TRACK_STATE.
// [asset, opened, closed, entry, stop, target, exit, qty, pnl USD, R, exit reason, days, market context at the signal]
export const TRACK = ${JSON.stringify(rows).replace(/\],\[/g, '],\n[')};
export const TRACK_STATE = ${JSON.stringify(st)};
// The rules' decision on each of the last 30 days, newest first (shown in "How the AI decided").
export const TRACK_DECISIONS = ${JSON.stringify(decisions)};
`);
const s = summary(trades);
console.log(`${FROM} → ${TO}: ${s.n} trades, win ${(s.winRate * 100).toFixed(1)}%, PF ${s.profitFactor.toFixed(2)}, ${((st.eq / st.start - 1) * 100).toFixed(2)}%, max DD ${(st.maxDD * 100).toFixed(1)}% · ${decisions.length} daily decisions`);
